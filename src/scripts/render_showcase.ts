#!/usr/bin/env tsx
/**
 * Render showcase evidence bundles into `docs/examples/bench/`
 * (road-to-a-baseline-that-has-to-catch-up step 1.2).
 *
 * Input: every `<stamp>-<task>/` bundle under `internal/bench/showcase/`
 * (shape: `_lib/showcase_bundle.ts`), the task list in that directory's
 * `PREDICTED-LIFT.md`, and claim statuses from `docs/CLAIMS.md`. Output: one
 * page per task with a bundle and an index listing EVERY task — a task with no
 * run says so, and a null or a loss is listed exactly like a pass. Every page
 * uses the same template, shows all k runs per arm with the median marked, and
 * names the claim it may be cited under; a bundle whose claim is not in the
 * ledger is refused (kill K1).
 *
 * Deterministic: same bundles, task list and ledger → byte-identical pages.
 * `--check` renders in memory and fails when any page differs from, is missing
 * against, or outlives its bundle.
 *
 * The default bundle root refuses a bundle marked `"fixture": true`, so a test
 * fixture can never be rendered as evidence; tests pass `--allow-fixture`.
 *
 * Exit: 0 ok · 1 `--check` drift · 2 bundle, ledger or usage error.
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import process from 'node:process';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { loadBundle, medianRun, type LoadedBundle, type ShowcaseArm, type ShowcaseRun, type TokenBuckets } from './_lib/showcase_bundle.js';
import { renderParity } from './_lib/showcase_parity_stats.js';

const _HERE = fileURLToPath(import.meta.url);
const REPO_ROOT = path.resolve(path.dirname(_HERE), '..', '..');
const GENERATED = '<!-- Generated by `render_showcase`';
const BUNDLE_DIR_RE = /^[0-9]{8}T[0-9]{6}Z-art-[a-z0-9-]+$/;
const TASK_HEADING_RE = /^## (art-[a-z0-9-]+) — (.+?) \(grader `([^`]+)`, claim `([a-z0-9-]+)`\)$/;

export interface RenderOptions {
    bundles: string;
    out: string;
    claims: string;
    tasks: string;
    allowFixture: boolean;
}

export interface TaskRow {
    id: string;
    title: string;
    grader: string;
    claim: string;
}

export class ShowcaseError extends Error {}

export function defaultOptions(): RenderOptions {
    const bundles = path.join(REPO_ROOT, 'internal', 'bench', 'showcase');
    return {
        bundles,
        out: path.join(REPO_ROOT, 'docs', 'examples', 'bench'),
        claims: path.join(REPO_ROOT, 'docs', 'CLAIMS.md'),
        tasks: path.join(bundles, 'PREDICTED-LIFT.md'),
        allowFixture: false,
    };
}

/** `### claim: <id>` blocks → their `- status:` value. */
export function parseClaimStatuses(text: string): Map<string, string> {
    const out = new Map<string, string>();
    let current: string | null = null;
    for (const line of text.split('\n')) {
        const head = /^### claim: ([a-z0-9-]+)\s*$/.exec(line);
        if (head) {
            current = head[1] as string;
            continue;
        }
        if (line.startsWith('#')) current = null;
        const status = /^- status:\s*(\S+)/.exec(line);
        if (current !== null && status && !out.has(current)) out.set(current, status[1] as string);
    }
    return out;
}

export function parseTaskRows(text: string): TaskRow[] {
    const rows: TaskRow[] = [];
    for (const line of text.split('\n')) {
        const m = TASK_HEADING_RE.exec(line);
        if (m) rows.push({ id: m[1] as string, title: m[2] as string, grader: m[3] as string, claim: m[4] as string });
    }
    return rows;
}

const posix = (p: string): string => p.split(path.sep).join('/');
const cell = (s: string): string => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const fmt = (n: number | null): string => (n === null ? 'unknown' : String(Number.isInteger(n) ? n : Number(n.toFixed(4))));

function medianOf(values: Array<number | null>): number | null {
    const xs = values.filter((v): v is number => v !== null).sort((a, b) => a - b);
    return xs.length === 0 ? null : (xs[Math.floor((xs.length - 1) / 2)] as number);
}

function worstCoverage(runs: readonly ShowcaseRun[]): TokenBuckets['coverage'] {
    if (runs.some((r) => r.tokens.coverage === 'unknown')) return 'unknown';
    return runs.some((r) => r.tokens.coverage === 'partial') ? 'partial' : 'complete';
}

function runCell(arm: ShowcaseArm, run: ShowcaseRun, medianNo: number | null, rel: string): string {
    const parts: string[] = [];
    if (run.thumbnail !== null) parts.push(`![${arm.label}, run ${run.run}](${rel}/${run.thumbnail})`);
    else parts.push('no image');
    if (run.infra_error !== null) parts.push(`infra error: ${cell(run.infra_error)}`);
    else parts.push(`score ${fmt(run.score)}${run.passed ? ' · bar reached' : ' · bar missed'}`);
    if (run.run === medianNo) parts.push('**median**');
    return parts.join('<br>');
}

export function renderPage(bundle: LoadedBundle, earlier: readonly LoadedBundle[], status: string, opts: RenderOptions): string {
    const s = bundle.summary;
    const rel = posix(path.relative(opts.out, bundle.dir));
    const L: string[] = [];
    L.push(`${GENERATED} from ${rel}/summary.json — do not edit; re-run the renderer. -->`);
    L.push('');
    L.push(`# ${s.task.id} — ${s.task.title}`);
    L.push('');
    if (s.fixture) {
        L.push('> **FIXTURE — not evidence.** Every number on this page is invented to test the renderer. Nothing here may be cited.');
        L.push('');
    }
    L.push('| Field | Value |');
    L.push('|---|---|');
    L.push(`| Claim | \`${s.claim_id}\` — status \`${status}\` in [CLAIMS.md](../../CLAIMS.md) |`);
    L.push(`| Primary grader | \`${s.task.primary_grader}\` |`);
    L.push(`| Parity bar | \`${s.task.parity_bar.metric} ${s.task.parity_bar.op} ${s.task.parity_bar.value}\` (fixed before any run) |`);
    L.push(`| Host | ${cell(s.host.name)} ${cell(s.host.version)} |`);
    L.push(`| Model | \`${s.model_id}\` |`);
    L.push(`| Runs per arm (k) | ${s.k} |`);
    L.push(`| Prices read on | ${s.pricing_sourced_on} |`);
    L.push(`| Verdict | \`${s.verdict.kind}\` — ${cell(s.verdict.reason)} |`);
    L.push(`| Bundle | \`${bundle.name}\` · sha256 \`${bundle.hash}\` |`);
    L.push('');
    L.push('## Prompt (verbatim, every arm)');
    L.push('');
    L.push('~~~text');
    L.push(s.task.prompt);
    L.push('~~~');
    L.push('');
    L.push('## Every run');
    L.push('');
    L.push('All k runs of every arm are shown; none is selected. **median** marks the lower-median first-shot score.');
    L.push('');
    L.push(`| Arm | ${s.arms[0]?.runs.map((r) => `Run ${r.run}`).join(' | ')} |`);
    L.push(`|---|${s.arms[0]?.runs.map(() => '---').join('|')}|`);
    for (const arm of s.arms) {
        const runs = arm.runs.slice().sort((a, b) => a.run - b.run);
        const med = medianRun(runs)?.run ?? null;
        L.push(`| ${cell(arm.label)} | ${runs.map((r) => runCell(arm, r, med, rel)).join(' | ')} |`);
    }
    L.push('');
    L.push('## Primary metrics, first shot');
    L.push('');
    L.push('Medians per run over the runs that reported the value; `unknown` where none did. Infra errors are reported and count against the arm.');
    L.push('');
    L.push('| Arm | Median score | Bar reached | Infra errors | Tokens in / out / cache read / cache write | Token coverage | Turns | Model requests | Tool calls | USD |');
    L.push('|---|---|---|---|---|---|---|---|---|---|');
    for (const arm of s.arms) {
        const r = arm.runs;
        const tok = (b: 'input' | 'output' | 'cache_read' | 'cache_write'): string => fmt(medianOf(r.map((x) => x.tokens[b])));
        L.push(
            `| ${cell(arm.label)} | ${fmt(medianRun(r)?.score ?? null)} | ${r.filter((x) => x.passed === true).length}/${s.k} | ${arm.infra_errors} | ` +
                `${tok('input')} / ${tok('output')} / ${tok('cache_read')} / ${tok('cache_write')} | ${worstCoverage(r)} | ` +
                `${fmt(medianOf(r.map((x) => x.turns)))} | ${fmt(medianOf(r.map((x) => x.model_requests)))} | ` +
                `${fmt(medianOf(r.map((x) => x.tool_calls)))} | ${fmt(medianOf(r.map((x) => x.usd)))} |`,
        );
    }
    const secondary = [...new Set(s.arms.flatMap((a) => a.runs.flatMap((r) => Object.keys(r.secondary))))].sort();
    if (secondary.length > 0) {
        L.push('');
        L.push('## Agent-config-native checks (secondary, never the verdict)');
        L.push('');
        L.push("These are this package's own checks. They are shown for context and decide nothing: the verdict rests on the primary grader only.");
        L.push('');
        L.push(`| Arm | ${secondary.map((k) => `${k} (median)`).join(' | ')} |`);
        L.push(`|---|${secondary.map(() => '---').join('|')}|`);
        for (const arm of s.arms) {
            L.push(`| ${cell(arm.label)} | ${secondary.map((k) => fmt(medianOf(arm.runs.map((r) => r.secondary[k] ?? null)))).join(' | ')} |`);
        }
    }
    L.push('');
    L.push(...renderParity(s));
    L.push('');
    L.push('## Reproduce');
    L.push('');
    L.push('~~~bash');
    L.push(s.reproduce);
    L.push('./scripts-run src/scripts/render_showcase');
    L.push('~~~');
    if (earlier.length > 0) {
        L.push('');
        L.push('## Earlier bundles');
        L.push('');
        for (const b of earlier) L.push(`- \`${b.name}\` · verdict \`${b.summary.verdict.kind}\` · sha256 \`${b.hash}\``);
    }
    L.push('');
    return L.join('\n');
}

export function renderIndex(rows: readonly TaskRow[], latest: ReadonlyMap<string, LoadedBundle>, statuses: ReadonlyMap<string, string>): string {
    const L: string[] = [];
    L.push(`${GENERATED} — do not edit; re-run the renderer. -->`);
    L.push('');
    L.push('# Benchmark examples — with and without agent-config');
    L.push('');
    L.push(
        'One page per artifact task, each comparing the same host and model with and without agent-config, scored by a grader ' +
            'agent-config does not own. Every task is listed, including nulls, losses and tasks that have not run. No figure here ' +
            'may be cited above the status of its claim in [CLAIMS.md](../../CLAIMS.md).',
    );
    L.push('');
    const real = [...latest.values()].filter((b) => !b.summary.fixture);
    if (real.length === 0) {
        L.push('**No showcase run has been recorded yet.** Every claim below is pre-registered and unmeasured; this page will list results, including nulls and losses, once a bundle exists.');
        L.push('');
    }
    L.push('| Task | Primary grader | Claim | Claim status | Latest bundle | Verdict |');
    L.push('|---|---|---|---|---|---|');
    for (const row of rows) {
        const b = latest.get(row.id);
        const status = statuses.get(row.claim) ?? 'not in ledger';
        const task = b ? `[${row.id}](${row.id}.md) — ${cell(row.title)}` : `${row.id} — ${cell(row.title)}`;
        const bundle = b ? `\`${b.name}\`${b.summary.fixture ? ' (FIXTURE)' : ''}` : '—';
        const verdict = b ? `\`${b.summary.verdict.kind}\`` : 'no run recorded';
        L.push(`| ${task} | \`${row.grader}\` | \`${row.claim}\` | \`${status}\` | ${bundle} | ${verdict} |`);
    }
    L.push('');
    return L.join('\n');
}

/** Render everything in memory: file name → content. Throws ShowcaseError on any invalid input. */
export function renderAll(opts: RenderOptions): Map<string, string> {
    const problems: string[] = [];
    if (!fs.existsSync(opts.claims)) throw new ShowcaseError(`claims ledger not found: ${opts.claims}`);
    const statuses = parseClaimStatuses(fs.readFileSync(opts.claims, 'utf8'));
    const rows = fs.existsSync(opts.tasks) ? parseTaskRows(fs.readFileSync(opts.tasks, 'utf8')) : [];
    const dirs = fs.existsSync(opts.bundles)
        ? fs.readdirSync(opts.bundles, { withFileTypes: true }).filter((d) => d.isDirectory() && BUNDLE_DIR_RE.test(d.name)).map((d) => d.name).sort()
        : [];
    const byTask = new Map<string, LoadedBundle[]>();
    for (const name of dirs) {
        const { bundle, problems: p } = loadBundle(path.join(opts.bundles, name));
        problems.push(...p);
        if (bundle === null) continue;
        if (bundle.summary.fixture && !opts.allowFixture) problems.push(`${name}: fixture bundle in the evidence tree — fixtures belong under tests/fixtures/`);
        if (!statuses.has(bundle.summary.claim_id)) problems.push(`${name}: claim ${bundle.summary.claim_id} is not in the ledger`);
        const list = byTask.get(bundle.summary.task.id) ?? [];
        list.push(bundle);
        byTask.set(bundle.summary.task.id, list);
    }
    for (const row of rows) if (!statuses.has(row.claim)) problems.push(`task ${row.id}: claim ${row.claim} is not in the ledger`);
    if (problems.length > 0) throw new ShowcaseError(problems.join('\n'));

    const known = new Set(rows.map((r) => r.id));
    const allRows = [...rows];
    for (const id of [...byTask.keys()].sort()) {
        if (known.has(id)) continue;
        const s = (byTask.get(id) as LoadedBundle[])[0]?.summary;
        if (s) allRows.push({ id, title: s.task.title, grader: s.task.primary_grader, claim: s.claim_id });
    }
    const latest = new Map<string, LoadedBundle>();
    const files = new Map<string, string>();
    for (const [id, list] of byTask) {
        const sorted = list.slice().sort((a, b) => b.summary.stamp.localeCompare(a.summary.stamp));
        const head = sorted[0] as LoadedBundle;
        latest.set(id, head);
        files.set(`${id}.md`, renderPage(head, sorted.slice(1), statuses.get(head.summary.claim_id) ?? 'not in ledger', opts));
    }
    files.set('index.md', renderIndex(allRows, latest, statuses));
    return files;
}

/** Generated pages present in `out` that the current render does not produce. */
function stalePages(out: string, expected: ReadonlyMap<string, string>): string[] {
    if (!fs.existsSync(out)) return [];
    return fs
        .readdirSync(out)
        .filter((f) => f.endsWith('.md') && !expected.has(f))
        .filter((f) => fs.readFileSync(path.join(out, f), 'utf8').startsWith(GENERATED))
        .sort();
}

const USAGE = 'usage: render_showcase [--check] [--bundles DIR] [--out DIR] [--claims FILE] [--tasks FILE] [--allow-fixture]\n';

export function main(argv: string[] = process.argv.slice(2)): number {
    const opts = defaultOptions();
    let check = false;
    for (let i = 0; i < argv.length; i += 1) {
        const a = argv[i];
        const value = (): string => {
            const v = argv[(i += 1)];
            if (v === undefined) throw new ShowcaseError(`${a} needs a value`);
            return path.resolve(v);
        };
        try {
            if (a === '-h' || a === '--help') {
                process.stdout.write(USAGE);
                return 0;
            } else if (a === '--check') check = true;
            else if (a === '--allow-fixture') opts.allowFixture = true;
            else if (a === '--bundles') {
                opts.bundles = value();
                opts.tasks = path.join(opts.bundles, 'PREDICTED-LIFT.md');
            } else if (a === '--out') opts.out = value();
            else if (a === '--claims') opts.claims = value();
            else if (a === '--tasks') opts.tasks = value();
            else {
                process.stderr.write(USAGE);
                return 2;
            }
        } catch (exc) {
            process.stderr.write(`render_showcase: error: ${(exc as Error).message}\n`);
            return 2;
        }
    }
    let files: Map<string, string>;
    try {
        files = renderAll(opts);
    } catch (exc) {
        if (exc instanceof ShowcaseError) {
            process.stderr.write(`render_showcase: error:\n${exc.message}\n`);
            return 2;
        }
        throw exc;
    }
    const stale = stalePages(opts.out, files);
    const drift = [...files].filter(([f, body]) => {
        const p = path.join(opts.out, f);
        return !fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== body;
    });
    if (check) {
        if (drift.length === 0 && stale.length === 0) {
            process.stdout.write(`render_showcase: clean — ${files.size} page(s) match their bundles.\n`);
            return 0;
        }
        for (const [f] of drift) process.stderr.write(`render_showcase: DRIFT — ${f} does not match its bundle\n`);
        for (const f of stale) process.stderr.write(`render_showcase: DRIFT — ${f} has no bundle any more\n`);
        process.stderr.write('render_showcase: re-run without --check.\n');
        return 1;
    }
    fs.mkdirSync(opts.out, { recursive: true });
    for (const [f, body] of drift) fs.writeFileSync(path.join(opts.out, f), body);
    for (const f of stale) fs.rmSync(path.join(opts.out, f));
    process.stdout.write(`render_showcase: ${drift.length} written, ${stale.length} removed, ${files.size - drift.length} unchanged.\n`);
    return 0;
}

function isCliEntry(): boolean {
    if (process.argv[1] === undefined) return false;
    if (import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) return true;
    try {
        return fs.realpathSync(_HERE) === fs.realpathSync(path.resolve(process.argv[1]));
    } catch {
        return false;
    }
}

if (isCliEntry()) {
    process.exitCode = main();
}
