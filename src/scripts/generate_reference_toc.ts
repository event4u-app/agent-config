#!/usr/bin/env tsx
/**
 * Heading index for long skill reference files
 * (road-to-steps-the-skill-cannot-skip 1.5).
 *
 * Every `src/skills/<skill>/references/**\/*.md` longer than MIN_LINES gets a
 * generated list of its `##` headings right under its title, so a reader who
 * opens the file sees where to go before line 30. The block is regenerated, never
 * written by hand: `task sync` runs this in write mode, and `--check` reports
 * drift without failing — the index is a reading aid, not a contract.
 *
 * Exit codes: 0 always, except 2 for an unknown flag.
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const MIN_LINES = 100;

const START = '<!-- reference-toc:start (generated by generate_reference_toc — do not edit) -->';
const END = '<!-- reference-toc:end -->';
const BLOCK = /\n?<!-- reference-toc:start[^\n]*-->\n[\s\S]*?<!-- reference-toc:end -->\n/;

const _HERE = fileURLToPath(import.meta.url);
const REPO_ROOT = path.resolve(path.dirname(_HERE), '..', '..');

/** GitHub's heading anchor: inline markup dropped, lower-cased, punctuation removed. */
function anchor(text: string): string {
    return text
        .replace(/`/g, '')
        .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
        .toLowerCase()
        .replace(/[^\p{L}\p{N}\s_-]/gu, '')
        .replace(/\s/g, '-');
}

/** `##` headings outside fenced blocks, in order. */
function headings(source: string): string[] {
    const out: string[] = [];
    let fence: string | null = null;
    for (const line of source.split('\n')) {
        const marker = /^\s*(`{3,}|~{3,})/.exec(line)?.[1];
        if (fence !== null) {
            if (marker !== undefined && marker[0] === fence[0] && marker.length >= fence.length) fence = null;
            continue;
        }
        if (marker !== undefined) {
            fence = marker;
            continue;
        }
        const h = /^## +(.+?)\s*#*\s*$/.exec(line);
        if (h !== null) out.push(h[1] as string);
    }
    return out;
}

/** The file with its index block regenerated, removed, or untouched. */
export function withToc(source: string): string {
    const bare = source.replace(BLOCK, '');
    const titles = headings(bare);
    if (bare.split('\n').length <= MIN_LINES || titles.length < 2) return bare;
    const seen = new Map<string, number>();
    const entries = titles.map((t) => {
        const base = anchor(t);
        const n = seen.get(base) ?? 0;
        seen.set(base, n + 1);
        const label = t.replace(/`/g, '').replace(/\[([^\]]*)\]\([^)]*\)/g, '$1');
        return `- [${label}](#${n === 0 ? base : `${base}-${n}`})`;
    });
    const block = `${START}\n**Contents**\n\n${entries.join('\n')}\n${END}\n`;
    const lines = bare.split('\n');
    const title = lines.findIndex((l) => /^# /.test(l));
    if (title === -1 || title > 10) return `${block}\n${bare}`;
    const before = lines.slice(0, title + 1).join('\n');
    const after = lines.slice(title + 1).join('\n');
    return `${before}\n\n${block}${after.startsWith('\n') ? after : `\n${after}`}`;
}

function referenceFiles(root: string): string[] {
    const skills = path.join(root, 'src', 'skills');
    if (!fs.existsSync(skills)) return [];
    const out: string[] = [];
    const walk = (dir: string): void => {
        for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
            const full = path.join(dir, e.name);
            if (e.isDirectory()) walk(full);
            else if (e.name.endsWith('.md')) out.push(full);
        }
    };
    for (const skill of fs.readdirSync(skills).sort()) {
        const refs = path.join(skills, skill, 'references');
        if (fs.existsSync(refs)) walk(refs);
    }
    return out.sort();
}

export function main(argv: string[] = process.argv.slice(2), root: string = REPO_ROOT): number {
    const unknown = argv.filter((a) => a !== '--check');
    if (unknown.length > 0) {
        process.stderr.write(`generate_reference_toc: unknown argument ${unknown[0]}\n`);
        return 2;
    }
    const check = argv.includes('--check');
    const files = referenceFiles(root);
    const drift: string[] = [];
    for (const file of files) {
        const source = fs.readFileSync(file, 'utf-8');
        const next = withToc(source);
        if (next === source) continue;
        drift.push(path.relative(root, file).split(path.sep).join('/'));
        if (!check) fs.writeFileSync(file, next, 'utf-8');
    }
    process.stdout.write(`scanned: ${files.length}\n`);
    if (check && drift.length > 0) {
        process.stdout.write(
            `⚠️  generate_reference_toc: ${drift.length} reference file(s) carry a stale heading index ` +
                '(warn-only — `task sync` regenerates it):\n',
        );
        for (const d of drift) process.stdout.write(`  ${d}\n`);
        return 0;
    }
    process.stdout.write(
        check
            ? `✅  generate_reference_toc: ${files.length} reference file(s), every heading index current.\n`
            : `✅  generate_reference_toc: ${drift.length} of ${files.length} reference file(s) rewritten.\n`,
    );
    return 0;
}

function isCliEntry(): boolean {
    if (process.argv[1] === undefined) return false;
    if (import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) return true;
    try {
        return fs.realpathSync(_HERE) === fs.realpathSync(path.resolve(process.argv[1]));
    } catch {
        return false;
    }
}

if (isCliEntry()) {
    process.exit(main());
}
