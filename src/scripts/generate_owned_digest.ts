#!/usr/bin/env tsx
/**
 * Writes `agents/roadmaps-owned.md`: one row per active, parked (`later/`) and
 * stub roadmap, naming what each one owns, so an intake session can shortlist
 * an existing owner before it writes a new file.
 *
 * The row holds only fields that change rarely — slug, directory, frontmatter
 * status, and the first sentence of `## Goal` (the H1 when there is none) — so
 * a checkbox flip or a new note never changes the digest. Paths are left out on
 * purpose: they churn with every edit and citation frequency is not ownership.
 *
 * The digest is a shortlist, never an owner decision: a reader confirms a
 * candidate by opening its roadmap. Over budget is a failure, never a
 * truncation, because a dropped tail row would hide an owner by sort order.
 *
 * Usage:
 *     tsx src/scripts/generate_owned_digest.ts            # rewrite in place
 *     tsx src/scripts/generate_owned_digest.ts --check    # exit 1 when stale or over budget
 *     tsx src/scripts/generate_owned_digest.ts --out PATH # write elsewhere
 *
 * Exit codes: 0 written / in sync · 1 stale or over budget · 2 usage.
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import process from 'node:process';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { is_roadmap_candidate as isRoadmapCandidate, parse_frontmatter as parseFrontmatter } from '../agent-src/scripts/update_roadmap_progress.js';
import { gpt_tokens } from './_lib/token_count.js';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

export const DIGEST = 'agents/roadmaps-owned.md';
export const GENERATOR = 'src/scripts/generate_owned_digest.ts';
export const ROADMAPS = 'agents/roadmaps';
/** `''` is the active top level. Order is the row order. */
export const DIRS = ['', 'later', 'stubs'] as const;
export const MAX_WORDS = 20;
export const BUDGET_TOKENS = 10_000;

export type Dir = (typeof DIRS)[number];

export interface Entry {
    readonly slug: string;
    readonly dir: Dir;
    readonly status: string;
    readonly owns: string;
}

function plain(s: string): string {
    return s
        .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
        .replace(/\*\*|__/g, '')
        .replace(/(^|[\s(])[*_]([^*_\s][^*_]*?)[*_](?=[\s).,;:]|$)/g, '$1$2')
        .replace(/\|/g, '\\|')
        .replace(/\s+/g, ' ')
        .trim();
}

function firstSentence(paragraph: string): string {
    const body = paragraph.replace(/^\s*(?:[-*+]|\d+\.)\s+/, '');
    const m = /^([\s\S]*?[.!?])(?=\s+[A-Z`(*"']|\s*$)/.exec(body);
    return m?.[1] ?? body;
}

function capWords(s: string, max: number): string {
    const words = s.split(' ').filter((w) => w !== '');
    return words.length <= max ? words.join(' ') : `${words.slice(0, max).join(' ')} …`;
}

/** What a roadmap owns, in at most {@link MAX_WORDS} words. */
export function describe(text: string): string {
    const goal = /^## Goal[^\n]*\n+([\s\S]*?)(?:\n\s*\n|\n## |(?![\s\S]))/m.exec(text);
    const source = goal?.[1]?.trim() ? firstSentence(goal[1]) : (/^# +(?:Roadmap: *|Stub: *)?(.+?)\s*$/m.exec(text)?.[1] ?? '');
    return capWords(plain(source), MAX_WORDS) || '—';
}

export function entryOf(dir: Dir, file: string, text: string): Entry {
    const status = parseFrontmatter(text)['status']?.trim();
    return { slug: file.replace(/\.md$/, ''), dir, status: status !== undefined && status !== '' ? status : '—', owns: describe(text) };
}

export function collect(root: string = REPO_ROOT): Entry[] {
    const out: Entry[] = [];
    for (const dir of DIRS) {
        const abs = path.join(root, ROADMAPS, dir);
        if (!fs.existsSync(abs)) continue;
        for (const file of fs.readdirSync(abs).sort()) {
            if (!file.endsWith('.md') || !isRoadmapCandidate(file)) continue;
            const full = path.join(abs, file);
            if (!fs.statSync(full).isFile()) continue;
            out.push(entryOf(dir, file, fs.readFileSync(full, 'utf8')));
        }
    }
    return out;
}

export function render(entries: readonly Entry[]): string {
    return [
        '<!-- GENERATED by `./scripts-run src/scripts/generate_owned_digest`; edit the roadmaps, never this file. -->',
        '',
        '# What each roadmap owns',
        '',
        // No row count in the header: every landing or archive would change that one line,
        // and two branches changing it always conflict where row edits rarely do.
        'A shortlist for intake: one row per active, parked (`later/`) and stub roadmap.',
        '`owns` is the first sentence of the file\'s `## Goal`, or its title when it has none, capped at',
        `${String(MAX_WORDS)} words. A row is a candidate, never an owner decision: open the roadmap to confirm it,`,
        'and keep the full search — this file only adds candidates to it.',
        '',
        '| slug | dir | status | owns |',
        '|---|---|---|---|',
        ...entries.map((e) => `| ${e.slug} | ${e.dir === '' ? 'active' : e.dir} | ${e.status} | ${e.owns} |`),
        '',
    ].join('\n');
}

export function overBudget(text: string, budget: number = BUDGET_TOKENS): string | null {
    const t = gpt_tokens(text);
    return t.tokens > budget ? `${DIGEST} is ${String(t.tokens)} tokens${t.exact ? '' : ' (estimated)'}, over its ${String(budget)}-token budget — shorten the goals or reopen the budget; the generator never truncates` : null;
}

export function main(argv: readonly string[] = process.argv.slice(2), root: string = REPO_ROOT): number {
    let check = false;
    let out: string | null = null;
    for (let i = 0; i < argv.length; i++) {
        if (argv[i] === '--check') check = true;
        else if (argv[i] === '--out' && argv[i + 1] !== undefined) out = argv[++i] as string;
        else {
            process.stderr.write(`unknown argument: ${String(argv[i])}\nusage: generate_owned_digest [--check | --out PATH]\n`);
            return 2;
        }
    }
    const text = render(collect(root));
    const over = overBudget(text);
    if (over !== null) {
        process.stderr.write(`${over}\n`);
        return 1;
    }
    const file = path.join(root, DIGEST);
    if (check) {
        const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
        if (current === text) return 0;
        process.stderr.write(`${DIGEST} is ${current === null ? 'missing' : 'stale'} — run ./scripts-run ${GENERATOR.replace(/\.ts$/, '')}\n`);
        return 1;
    }
    fs.writeFileSync(out ?? file, text);
    return 0;
}

function _isCliEntry(): boolean {
    if (process.argv[1] === undefined) return false;
    if (import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) return true;
    try {
        return fs.realpathSync(fileURLToPath(import.meta.url)) === fs.realpathSync(path.resolve(process.argv[1]));
    } catch {
        return false;
    }
}

if (_isCliEntry()) {
    process.exitCode = main();
}
