/**
 * A raise reason must be a sentence, not the number restated.
 *
 * The floor is a length plus a digit-density test: "raised to 4200" and "4200"
 * both fail, "moved because X landed and the body grew for reason Y" passes.
 * Mechanical, not editorial — a reason can be wrong, which is a review problem.
 */
const MIN_REASON_CHARS = 40;

/** Phrasings that are present but say nothing. Mirrors the ledger gate's denylist. */
const EMPTY_REASONS = [
    'n/a',
    'none',
    'tbd',
    'see above',
    'no reason',
    'raise',
    'raised',
    'update',
    'updated',
    'adjusted',
    'refresh',
];

/**
 * Matches a migration pointer and captures its target.
 *
 * Two target shapes ship in the corpus: a markdown link, where the href is the
 * target and the label is decorative, and a bare backticked token. Anchored on
 * the verb rather than on `Body …` because one live phrasing is mid-sentence
 * ("Portability body migrated to X. Sync body migrated to Y") and two are
 * soft-wrapped across lines — so this runs over the joined body.
 */
const POINTER_RE = /\b(?:migrated to|merged into)\s+(?:\[[^\]]*\]\(([^)\s]+)\)|`([^`]+)`)/gi;

/** An Iron Law heading at any level, including the numbered variants. */
const IRON_LAW_HEADING_RE = /^#{1,6}\s+(?:The\s+)?Iron\s+Laws?\b/i;

/** A capitalised negation clause — the load-bearing exception denials. */
const NEGATION_RE = /\b(?:NEVER|NO|NOT|DO NOT)\b/;

export interface PointerRow {
    /** Rule stem, e.g. `context-hygiene`. */
    rule: string;
    /** Raw target as written in the pointer. */
    target: string;
    /** Repo-relative path it resolved to, or null when unresolved. */
    resolved: string | null;
    /** Candidate paths tried, for the failure message. */
    tried: string[];
}

export interface RuleRow {
    rule: string;
    /** Exact-BPE tokens of the whole file, frontmatter included — the payload. */
    tokens: number;
    /** Exact-BPE tokens of the body alone. THIS is what the ceiling is keyed on. */
    body_tokens: number;
    /**
     * Tokens of the YAML frontmatter.
     *
     * Reported as its own column so `fm + floor + residue` reconciles against
     * `tokens`. Without it the table's columns do not add up, which invites a
     * reader to distrust every row — and the frontmatter is real payload: it is
     * what the emitter reads to decide whether the rule loads at all.
     */
    frontmatter_tokens: number;
    /** Tokens of lines classified floor by the criterion above. */
    floor_tokens: number;
    /** Tokens of everything else in the body. */
    residue_tokens: number;
    pointers: PointerRow[];
    /** True when `migratedRules()` sees this rule but POINTER_RE parsed no target. */
    unparsed: boolean;
    /** True when the opening `---` never closes — measured as zero, so say so. */
    malformed_frontmatter: boolean;
}

/**
 * Resolve a pointer target to a repo-relative path.
 *
 * Reuses `rule_backlinks.candidate_paths` for the `skill:` / `guideline:` /
 * `context:` / `contract:` / repo-path shapes rather than restating them, and
 * `check_references`'s prefix strategy for relative hrefs rather than inventing
 * a second one. A bare word with no shape falls back to a sibling rule, the one
 * form `brand-consistency` uses ("merged into `brand-source-of-truth`").
 *
 * **Why a relative href is not resolved relative to `src/rules/`.** That was the
 * first implementation and it reported 12 of 44 pointers broken — a false red.
 * Rule bodies are authored for the PROJECTED tree, where `../docs/` is the
 * sibling docs directory; under `src/rules/` the same href points at
 * `src/docs/`, which does not exist. `check_references` already solved this by
 * stripping leading `./` / `../` and trying `[root, dist/agent-src, src,
 * src/agent-src]`, and a second convention here would disagree with the gate
 * consumers already trust. Adopted verbatim.
 */
export function resolvePointer(root: string, raw: string): { resolved: string | null; tried: string[] } {
    // Anchors are part of the link, never part of the file identity.
    const bare = raw.split('#')[0]!.trim();
    if (bare === '') return { resolved: null, tried: [] };

    const tried: string[] = [];

    if (bare.startsWith('.') || bare.includes('/')) {
        const stripped = bare.replace(/^[./]+/, '');
        // Prefix ORDER deviates from check_references on purpose, and it is the
        // one place it does: `dist/agent-src/` is a TRACKED projection, so trying
        // it before `src/` lets a pointer resolve against a stale copy after its
        // real target is deleted and `task sync` is not re-run in the same
        // commit — the gate would report a genuinely broken pointer as resolved.
        // The source of truth is tried first; the projection stays in the list as
        // a last resort so a target that legitimately lives only there still
        // resolves.
        for (const prefix of ['', 'src', 'src/agent-src', 'dist/agent-src']) {
            const rel = path.normalize(path.join(prefix, stripped));
            tried.push(rel);
            if (isFile(root, rel)) return { resolved: rel, tried };
        }
        // Also as written from the rule's own directory, which is how a
        // same-directory sibling link (`brand-source-of-truth.md`) resolves.
        const sibling = path.normalize(path.join(RULES_REL, bare));
        tried.push(sibling);
        if (isFile(root, sibling)) return { resolved: sibling, tried };
    }

    const shaped = candidate_paths(bare);
    if (shaped !== null) {
        for (const rel of shaped) {
            tried.push(rel);
            if (isFile(root, rel)) return { resolved: rel, tried };
        }
    }

    // Bare stem → a sibling rule.
    if (/^[a-z0-9][a-z0-9_.-]*$/i.test(bare)) {
        const rel = path.join(RULES_REL, `${bare.replace(/\.md$/, '')}.md`);
        tried.push(rel);
        if (isFile(root, rel)) return { resolved: rel, tried };
    }

    return { resolved: null, tried };
}

/**
 * A pointer target must be a readable FILE.
 *
 * `existsSync` alone accepts a directory, so a pointer rewritten to
 * `../docs/guidelines` — or a `skill:` target whose `SKILL.md` was deleted while
 * its directory survived — would report "resolves: yes" while naming no
 * document. The whole assertion is that a reader following the pointer finds
 * something to read.
 */
function isFile(root: string, rel: string): boolean {
    try {
        return fs.statSync(path.join(root, rel)).isFile();
    } catch {
        return false;
    }
}

/**
 * Split a rule file into its YAML frontmatter and its body.
 *
 * A file that ends AT its closing `---` with no trailing newline has no body,
 * and that is a real answer rather than a parse failure — but it used to be
 * indistinguishable from "no frontmatter found", which would have let such a
 * rule contribute zero residue silently. The two cases are returned apart so the
 * caller can say which one it saw.
 */
function splitFrontmatter(text: string): {
    frontmatter: string;
    body: string;
    /** False when the opening `---` never closes — a malformed file, not an empty one. */
    parsed: boolean;
} {
    if (!text.startsWith('---')) return { frontmatter: '', body: text, parsed: true };
    const end = text.indexOf('\n---', 3);
    if (end === -1) return { frontmatter: '', body: text, parsed: false };
    const nl = text.indexOf('\n', end + 1);
    if (nl === -1) return { frontmatter: text, body: '', parsed: true };
    return { frontmatter: text.slice(0, nl + 1), body: text.slice(nl + 1), parsed: true };
}

/**
 * Split a body into floor and residue lines by the stated criterion.
 *
 * Floor: an Iron Law heading; every line of a fenced block opened while inside
 * an Iron Law section; any line carrying a capitalised negation clause; the
 * pointer sentence itself. Everything else is residue.
 *
 * The Iron-Law-section boundary is the next heading at the same level or
 * shallower — a `###` inside an `## Iron Law` stays inside it, which matters
 * because demotion is the norm in these files.
 */
export function splitFloorResidue(body: string): { floor: string[]; residue: string[] } {
    const floor: string[] = [];
    const residue: string[] = [];
    let ironLevel: number | null = null;
    // The OPENING marker, not a boolean: ``` and ~~~ are not interchangeable.
    // Treating them as one closes the outer fence at the inner opener, and the
    // house `markdown-safe-codeblocks` shape is precisely ``` nested inside ~~~ —
    // so the interchangeable version mis-splits every rule that follows it.
    let fenceMarker: string | null = null;
    // A pointer sentence soft-wraps across lines in the live corpus, which is why
    // `readRules` matches on the joined body. Classifying per line would put the
    // continuation into residue, biasing the split in the direction this
    // roadmap's own premise favours. Continuation runs to the blank line that
    // ends the paragraph.
    let inPointerParagraph = false;

    for (const line of body.split('\n')) {
        const opener = /^\s*(```|~~~)/.exec(line);
        const heading = /^(#{1,6})\s/.exec(line);

        if (fenceMarker !== null) {
            (ironLevel !== null ? floor : residue).push(line);
            if (opener !== null && opener[1] === fenceMarker) fenceMarker = null;
            continue;
        }

        if (IRON_LAW_HEADING_RE.test(line)) {
            ironLevel = heading?.[1]!.length ?? 2;
            inPointerParagraph = false;
            floor.push(line);
            continue;
        }

        if (heading !== null && ironLevel !== null && heading[1]!.length <= ironLevel) {
            ironLevel = null;
        }
        if (heading !== null) inPointerParagraph = false;

        if (opener !== null) {
            fenceMarker = opener[1]!;
            inPointerParagraph = false;
            (ironLevel !== null ? floor : residue).push(line);
            continue;
        }

        POINTER_RE.lastIndex = 0;
        const pointerHere = POINTER_RE.test(line);
        POINTER_RE.lastIndex = 0;
        if (pointerHere) inPointerParagraph = true;
        else if (line.trim() === '') inPointerParagraph = false;

        if (ironLevel !== null || NEGATION_RE.test(line) || inPointerParagraph) {
            floor.push(line);
            continue;
        }
        residue.push(line);
    }

    return { floor, residue };
}

/**
 * Measure every rule carrying a migration pointer.
 *
 * `withSplit` controls the floor/residue tokenisation. The check path needs only
 * the body total, so it skips three of the four encodes per rule — the split is
 * a reporting concern and no verdict depends on it.
 */
export function readRules(root: string, withSplit = false): { rows: RuleRow[]; scanned: number } {
    const dir = path.join(root, RULES_REL);
    let names: string[];
    try {
        names = fs.readdirSync(dir).filter((n) => n.endsWith('.md')).sort();
    } catch {
        return { rows: [], scanned: 0 };
    }

    // The ledger gate's broad matcher is the denominator: a rule it sees and this
    // gate cannot parse is a phrasing drift, reported rather than skipped. It is
    // deliberately unbounded, so a rule it matches counts only when the migration
    // ledger also holds a record for it — see the docblock.
    const broad = new Set(migratedRules(root));
    const rows: RuleRow[] = [];

    for (const n of names) {
        const stem = n.slice(0, -3);
        const text = fs.readFileSync(path.join(dir, n), 'utf8');
        const joined = text.replace(/\s*\n\s*/g, ' ');

        const pointers: PointerRow[] = [];
        POINTER_RE.lastIndex = 0;
        for (const m of joined.matchAll(POINTER_RE)) {
            const raw = (m[1] ?? m[2] ?? '').trim();
            const { resolved, tried } = resolvePointer(root, raw);
            pointers.push({ rule: stem, target: raw, resolved, tried });
        }

        const ledgered = isFile(root, path.join(LEDGER_DIR_REL, `${stem}.yml`));
        if (pointers.length === 0 && !(broad.has(stem) && ledgered)) continue;

        const { frontmatter, body, parsed } = splitFrontmatter(text);
        const split = withSplit
            ? splitFloorResidue(body)
            : { floor: [] as string[], residue: [] as string[] };
        rows.push({
            rule: stem,
            tokens: gpt_tokens(text).tokens,
            body_tokens: gpt_tokens(body).tokens,
            frontmatter_tokens: gpt_tokens(frontmatter).tokens,
            floor_tokens: withSplit ? gpt_tokens(split.floor.join('\n')).tokens : 0,
            residue_tokens: withSplit ? gpt_tokens(split.residue.join('\n')).tokens : 0,
            pointers,
            unparsed: pointers.length === 0,
            malformed_frontmatter: !parsed,
        });
    }

    return { rows, scanned: names.length };
}

