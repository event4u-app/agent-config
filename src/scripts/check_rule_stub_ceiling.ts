/**
 * A raise reason must be a sentence, not the number restated.
 *
 * Mechanical, not editorial: a length floor, a denylist of known-empty
 * phrasings, and a letters-remain test so "raised to 4200" and "4200" both fail
 * while a real explanation passes. A reason can still be WRONG — that is a
 * review problem, and no lint can be its judge.
 */
export function isRealReason(reason: unknown): boolean {
    if (typeof reason !== 'string') return false;
    const trimmed = reason.trim();
    // Denylist FIRST. Behind the length floor it was unreachable dead code —
    // every entry is shorter than the floor, so `includes()` could never be the
    // deciding check and the docblock advertised a mechanism that never ran.
    // Ahead of it, the list does the job it was written for: rejecting a padded
    // restatement such as "updated ................................".
    if (EMPTY_REASONS.some((e) => trimmed.toLowerCase().startsWith(e))) return false;
    if (trimmed.length < MIN_REASON_CHARS) return false;
    return /[a-z]{4}/i.test(trimmed.replace(/\d/g, ''));
}

/**
 * The LATEST raise per rule, which is the only one the committed ceiling can match.
 *
 * Checking every entry against the ceiling made the history array hold at most
 * one entry per rule: a second raise turned the first, correct, historical row
 * into a permanent red whose only cure was deleting the audit trail the array
 * exists to hold. Later entries win; earlier ones are history, which is the point.
 */
export function latestRaises(
    history: readonly { rule?: unknown; from?: unknown; to?: unknown; reason?: unknown }[],
): Map<string, { from: number; to: number; reason: unknown }> {
    const out = new Map<string, { from: number; to: number; reason: unknown }>();
    for (const h of history) {
        if (typeof h.rule !== 'string') continue;
        if (typeof h.from !== 'number' || typeof h.to !== 'number') continue;
        if (!(h.to > h.from)) continue;
        const seen = out.get(h.rule);
        if (seen === undefined || h.to >= seen.to) out.set(h.rule, { from: h.from, to: h.to, reason: h.reason });
    }
    return out;
}

/**
 * The commit the baseline was measured at.
 *
 * Read from git rather than left to an env var nobody documents: the sibling
 * baseline records a real sha, and a ceiling disputed months later cannot be
 * told apart from drift when its own file says `unrecorded`. The env var still
 * wins where a caller sets it deliberately.
 */
function headCommit(root: string): string | null {
    const res = spawnSync('git', ['rev-parse', '--short', 'HEAD'], {
        cwd: root,
        encoding: 'utf-8',
    });
    const out = (res.stdout ?? '').trim();
    return res.status === 0 && out !== '' ? out : null;
}

/** Markdown table for the Phase-0 evidence artifact. */
export function renderReport(rows: RuleRow[]): string {
    const total = rows.reduce((a, r) => a + r.tokens, 0);
    const fm = rows.reduce((a, r) => a + r.frontmatter_tokens, 0);
    const body = rows.reduce((a, r) => a + r.body_tokens, 0);
    const floor = rows.reduce((a, r) => a + r.floor_tokens, 0);
    const residue = rows.reduce((a, r) => a + r.residue_tokens, 0);
    const out: string[] = [];
    out.push(`| rule | tokens | frontmatter | body (ceiling) | floor | residue | pointer target | resolves |`);
    out.push(`|---|---:|---:|---:|---:|---:|---|---|`);
    for (const r of rows.slice().sort((a, b) => b.residue_tokens - a.residue_tokens)) {
        const targets = r.pointers.length === 0 ? '(unparsed)' : r.pointers.map((p) => `\`${p.target}\``).join(' · ');
        const ok = r.pointers.length === 0 ? '—' : r.pointers.every((p) => p.resolved !== null) ? 'yes' : 'NO';
        out.push(
            `| \`${r.rule}\` | ${r.tokens} | ${r.frontmatter_tokens} | ${r.body_tokens} | ` +
                `${r.floor_tokens} | ${r.residue_tokens} | ${targets} | ${ok} |`,
        );
    }
    out.push(
        `| **total (${rows.length} rules)** | **${total}** | **${fm}** | **${body}** | ` +
            `**${floor}** | **${residue}** | | |`,
    );
    // BPE is not additive across a split: merges that span a segment boundary are
    // lost when the segments are encoded separately. Stating the residual is the
    // honest form — a reader who adds the columns WILL find it, and a table that
    // silently does not reconcile is worse than one that says by how much.
    const parts = fm + floor + residue;
    out.push('');
    out.push(
        `Column residual: \`frontmatter + floor + residue\` = ${parts} against ` +
            `${total} whole-file tokens (${parts - total >= 0 ? '+' : ''}${parts - total}, ` +
            `${(Math.abs(parts - total) / Math.max(total, 1) * 100).toFixed(2)} %), and ` +
            `\`frontmatter + body\` = ${fm + body}. BPE is not additive across segment ` +
            'boundaries — merges spanning a split are lost when the segments are encoded ' +
            'separately. **The ceilings are keyed on the `body (ceiling)` column**, not on ' +
            'the whole file: frontmatter is the routing surface, and a rule that gains a ' +
            'trigger must not trip a prose ceiling.',
    );
    return out.join('\n');
}

export function main(): number {
    if (ARGV.includes('--self-test')) {
        return selfTest(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..'));
    }
    const root = process.cwd();

    let reading: { rows: RuleRow[]; scanned: number };
    try {
        reading = readRules(root);
        assertScanned({
            gate: GATE,
            scanned: reading.scanned,
            units: 'rule file(s)',
            roots: [RULES_REL],
        });
    } catch (err) {
        if (err instanceof DeadScopeError) {
            process.stderr.write(`❌  ${err.message}\n`);
            return 1;
        }
        throw err;
    }

    const rows = reading.rows;

    if (REPORT) {
        process.stdout.write(`${renderReport(readRules(root, true).rows)}\n`);
        return 0;
    }

    const baseline_path = path.join(root, BASELINE_REL);

    if (WRITE) {
        const prior: Ceilings | null = fs.existsSync(baseline_path)
            ? (JSON.parse(fs.readFileSync(baseline_path, 'utf8')) as Ceilings)
            : null;
        const ceilings: Record<string, number> = {};
        for (const r of rows.slice().sort((a, b) => a.rule.localeCompare(b.rule))) {
            ceilings[r.rule] = r.body_tokens;
        }

        // THE WRITE PATH IS WHERE THE RAISE ASSERTION LIVES OR DIES.
        //
        // Recomputing every ceiling from the tree and carrying `history` forward
        // verbatim would make assertion 3 decorative: a rule grows past its
        // ceiling, CI reds, and the failure text plus the baseline comment both
        // point the operator at THIS command, which would silently re-anchor the
        // whole corpus upward with `history` still empty. Worse, regeneration is
        // the mandated fix for a newly migrated rule, so the silent raise would
        // ride along with ordinary correct work.
        //
        // So a raise no history entry covers is REFUSED here. Lowering, and
        // adding a rule that has no ceiling yet, both pass untouched — those are
        // the moves the ratchet exists to allow.
        const covered = latestRaises(prior?.history ?? []);
        const unstated: string[] = [];
        for (const [rule, next_ceiling] of Object.entries(ceilings)) {
            const before = prior?.ceilings?.[rule];
            if (before === undefined || next_ceiling <= before) continue;
            const entry = covered.get(rule);
            if (entry === undefined || entry.to < next_ceiling || !isRealReason(entry.reason)) {
                unstated.push(
                    `\`${rule}\`: ${before} → ${next_ceiling} (+${next_ceiling - before})`,
                );
            }
        }
        if (unstated.length > 0) {
            process.stderr.write(
                `❌  ${GATE}: refusing to write — ${unstated.length} ceiling(s) would RISE with ` +
                    'no history entry covering them.\n\n',
            );
            for (const u of unstated) process.stderr.write(`    • ${u}\n`);
            process.stderr.write(
                '\n    A raise is a stated decision. Either move the prose to the pointer target\n' +
                    '    (never delete it — `preservation-guard` binds), or add a `history` entry\n' +
                    `    per rule: {date, rule, from, to, reason} with a reason of at least\n` +
                    `    ${MIN_REASON_CHARS} characters saying what landed, then re-run this command.\n`,
            );
            return 1;
        }

        const next: Ceilings = {
            _comment: ceilingComment(),
            measured_at_commit:
                process.env['AGENT_CONFIG_BASELINE_COMMIT'] ?? headCommit(root) ?? 'unrecorded',
            tokens_exact: TIKTOKEN_AVAILABLE,
            ceilings,
            history: prior?.history ?? [],
        };
        fs.writeFileSync(baseline_path, `${JSON.stringify(next, null, 4)}\n`);
        process.stdout.write(
            `✅  ${GATE}: baseline written — ${Object.keys(ceilings).length} migrated rule(s) ` +
                `at ${next.measured_at_commit} ` +
                `(${next.tokens_exact ? 'exact BPE' : 'character proxy'}).\n`,
        );
        return 0;
    }

    if (!fs.existsSync(baseline_path)) {
        process.stderr.write(
            `❌  ${GATE}: no baseline at ${BASELINE_REL}. Run with --write-baseline once, ` +
                'commit the file, and the ceilings are live from then on.\n',
        );
        return 1;
    }

    const base = JSON.parse(fs.readFileSync(baseline_path, 'utf8')) as Ceilings;
    const failures: string[] = [];
    const ledger = new GateLedger(GATE);
    ledger.plan(rows.map((r) => r.rule));

    // A method change would report a measurement delta as a payload delta.
    // Say so instead of ratcheting — same posture as the census weight axis.
    if (base.tokens_exact !== TIKTOKEN_AVAILABLE) {
        // NOT `complete` — the run failed, and a ledger line reporting 44 clean
        // targets on a failed run is the gate-green-while-blind shape the ledger
        // exists to make visible.
        for (const r of rows) ledger.fail(r.rule, 'measurement method changed; ceiling unresolved');
        ledger.report();
        process.stdout.write(`scanned: ${reading.scanned}\n`);
        process.stderr.write(
            `❌  ${GATE}: token measurement METHOD changed (baseline ` +
                `${base.tokens_exact ? 'exact' : 'proxy'} → current ` +
                `${TIKTOKEN_AVAILABLE ? 'exact' : 'proxy'}). The ceilings are UNRESOLVED, not ` +
                'red: re-anchor in the same environment rather than reading a method delta as ' +
                'a corpus delta.\n',
        );
        return 1;
    }

    // Every declared raise must carry a real reason, checked INDEPENDENTLY of
    // whether any rule is currently over its ceiling.
    //
    // The first implementation consulted the reason only inside the
    // `tokens > ceiling` branch, which made it unreachable in practice: a raise
    // is precisely the act that puts the rule back UNDER its ceiling, so the
    // branch that would have checked the reason never ran. The gate's own
    // self-test caught it. The requirement belongs to the baseline's integrity,
    // not to the rule's current size.
    // EVERY entry must carry a real reason — an unstated raise is unstated
    // whether or not a later one superseded it.
    for (const h of base.history ?? []) {
        if (typeof h.rule !== 'string' || !(h.to > h.from)) continue;
        if (!isRealReason(h.reason)) {
            failures.push(
                `baseline history raises \`${h.rule}\` ${h.from} → ${h.to} with no real reason ` +
                    `(got ${JSON.stringify(h.reason ?? null)}). A raise is a stated decision: ` +
                    `write the sentence that says what landed and why the ceiling moves with it. ` +
                    `Raising a ceiling to clear a red is the config-weakening move this repo ` +
                    `blocks by construction.`,
            );
        }
    }

    // Only the LATEST raise per rule is compared against the committed ceiling.
    // Comparing every entry capped the history at one row per rule: a second
    // raise turned the first, correct, historical entry into a permanent red
    // whose only cure was deleting the audit trail.
    const raised = latestRaises(base.history ?? []);
    for (const [rule, entry] of raised) {
        const committed = base.ceilings[rule];
        if (committed !== undefined && committed !== entry.to) {
            failures.push(
                `baseline history says \`${rule}\` was last raised to ${entry.to}, but its ` +
                    `committed ceiling is ${committed}. The history and the ceilings disagree, ` +
                    `which is the signature of a hand-edited count — regenerate with ` +
                    `--write-baseline instead of editing the number.`,
            );
        }
    }

    for (const r of rows) {
        const reasons: string[] = [];

        if (r.unparsed) {
            reasons.push(
                'carries a migration line the ledger gate sees, but no target this gate can ' +
                    'parse. A reworded pointer must surface as a finding, never as silence — ' +
                    'either restore a parseable target or extend POINTER_RE with the new form',
            );
        }
        for (const p of r.pointers) {
            if (p.resolved === null) {
                reasons.push(
                    `migration pointer target \`${p.target}\` resolves to nothing (tried: ` +
                        `${p.tried.length > 0 ? p.tried.join(', ') : 'no known shape'})`,
                );
            }
        }

        if (r.malformed_frontmatter) {
            reasons.push(
                'its opening `---` never closes, so the body measured as empty. That is a ' +
                    'malformed file rather than a small one, and it would otherwise contribute ' +
                    'zero residue with no signal',
            );
        }

        const ceiling = base.ceilings[r.rule];
        if (ceiling === undefined) {
            reasons.push(
                `no ceiling in ${BASELINE_REL}. A newly migrated rule needs one: re-anchor with ` +
                    '--write-baseline in the same commit that adds the pointer',
            );
        } else if (r.body_tokens > ceiling) {
            // The write path refuses an uncovered raise, so reaching here means
            // the committed ceiling is below the tree. A covering history entry
            // cannot rescue it: `latestRaises` already required entry.to to EQUAL
            // the committed ceiling, so entry.to >= body_tokens > ceiling == entry.to
            // is a contradiction. The overflow is simply real.
            reasons.push(
                `body grew past its ceiling (${ceiling} → ${r.body_tokens} tokens, ` +
                    `+${r.body_tokens - ceiling}). A migrated rule is held at the size its pointer ` +
                    'claims. Move the prose to the pointer target — never delete it, ' +
                    '`preservation-guard` binds — or raise the ceiling with a `history` entry ' +
                    'whose reason is a real sentence, which --write-baseline then accepts',
            );
        }

        if (reasons.length > 0) {
            ledger.fail(r.rule, reasons[0]!);
            for (const reason of reasons) failures.push(`\`${r.rule}\`: ${reason}`);
        } else {
            ledger.complete(r.rule);
        }
    }

    ledger.report();

    // Exactly one `scanned: <N>` line, on BOTH paths and regardless of --quiet: a
    // gate that goes blind must be detectable on the run where it says nothing
    // else. Contract rule 1 of `src/config/gate-coverage.yml`. Emitted BEFORE the
    // failure return — behind it, a real violation earned a second, misleading
    // red from check_gate_coverage about blindness rather than about the finding.
    process.stdout.write(`scanned: ${reading.scanned}\n`);

    if (failures.length > 0) {
        process.stderr.write(`❌  ${GATE}: a migrated rule stopped matching its own pointer.\n\n`);
        for (const f of failures) process.stderr.write(`    • ${f}\n`);
        process.stderr.write(
            '\n    The pointer is a claim the rule makes about itself. This gate holds it —\n' +
                '    the point is that a change is stated, not that it is forbidden.\n',
        );
        return 1;
    }

    if (!QUIET) {
        // No residue figure here, deliberately. The check path skips the
        // floor/residue encodes, so printing that sum would print a zero this run
        // never computed — a number nothing measured is worse than no number.
        // `--report` is where the split lives.
        const body = rows.reduce((a, r) => a + r.body_tokens, 0);
        process.stdout.write(
            `✅  ${GATE}: ${rows.length} migrated rule(s) under ceiling · ` +
                `${rows.reduce((a, r) => a + r.pointers.length, 0)} pointer(s) resolved · ` +
                `${body} body tokens ` +
                `(${TIKTOKEN_AVAILABLE ? 'exact BPE' : 'character proxy'}) · ` +
                `${reading.scanned} rule file(s).\n`,
        );
    }
    return 0;
}

/** A migrated rule whose pointer resolves, used as the accept fixture. */
const FIXTURE_TARGET_REL = path.join('docs', 'guidelines', 'alpha-mechanics.md');
const FIXTURE_OK = [
    '---',
    'type: "auto"',
    '---',
    '',
    '# Alpha',
    '',
    '## The Iron Law',
    '',
    '```',
    'NEVER DO THE WRONG THING.',
    '```',
    '',
    'Body migrated to `guideline:alpha-mechanics` (per P4 of the router roadmap).',
    '',
].join('\n');

interface FixtureShape {
    /** Write the rule + its pointer target. Off for the dead-scope case. */
    rules: boolean;
    /** Write the pointer target file. Off for the unresolved-pointer case. */
    target?: boolean;
    /** Write a baseline at all. Off for the missing-baseline case. */
    baseline: boolean;
    /** Extra body appended to the rule AFTER the baseline is derived. */
    pad?: string;
    /** Replace the pointer line, to test the unparsed-phrasing path. */
    rewordPointer?: string;
    /** Mutate the derived baseline before writing. */
    tamper?: (b: Ceilings) => void;
}

/**
 * Build a throwaway tree the gate can run against.
 *
 * The baseline is DERIVED by the same `readRules` the gate uses, then the rule is
 * optionally padded. Hand-writing an expected token total would make the accept
 * case a test of my arithmetic rather than of the gate.
 */
function buildFixture(dir: string, shape: FixtureShape): string {
    fs.mkdirSync(path.join(dir, RULES_REL), { recursive: true });
    fs.mkdirSync(path.join(dir, 'src', 'config'), { recursive: true });
    fs.mkdirSync(path.join(dir, LEDGER_DIR_REL), { recursive: true });
    fs.mkdirSync(path.join(dir, path.dirname(FIXTURE_TARGET_REL)), { recursive: true });

    // The migration ledger bounds the broad matcher, so the fixture needs one for
    // the reworded-pointer case to be a finding rather than a skip.
    fs.writeFileSync(path.join(dir, LEDGER_DIR_REL, 'alpha.yml'), 'rule: alpha\n');

    const rulePath = path.join(dir, RULES_REL, 'alpha.md');
    if (shape.rules) {
        let body = FIXTURE_OK;
        if (shape.rewordPointer !== undefined) {
            body = body.replace(
                'Body migrated to `guideline:alpha-mechanics` (per P4 of the router roadmap).',
                shape.rewordPointer,
            );
        }
        fs.writeFileSync(rulePath, body);
    }
    if (shape.target !== false) {
        fs.writeFileSync(path.join(dir, FIXTURE_TARGET_REL), '# Alpha mechanics\n');
    }

    if (shape.baseline) {
        const derived = shape.rules ? readRulesIn(dir) : [];
        const ceilings: Record<string, number> = {};
        for (const r of derived) ceilings[r.rule] = r.body_tokens;
        const base: Ceilings = {
            _comment: 'self-test fixture',
            measured_at_commit: 'fixture',
            tokens_exact: TIKTOKEN_AVAILABLE,
            ceilings,
            history: [],
        };
        shape.tamper?.(base);
        fs.writeFileSync(path.join(dir, BASELINE_REL), `${JSON.stringify(base, null, 4)}\n`);
    }

    // Padding lands AFTER the baseline so the fixture grows against its own ceiling.
    if (shape.rules && shape.pad !== undefined) {
        fs.appendFileSync(rulePath, shape.pad);
    }
    return dir;
}

/** `readRules` against an arbitrary root — the fixture builder's measurement path. */
function readRulesIn(dir: string): RuleRow[] {
    return readRules(dir, true).rows;
}

/**
 * Prove the gate discriminates rather than merely exits.
 *
 * The rejecting cases are the ways this gate is worth having: a broken pointer
 * target, a rule grown past its ceiling, a raise with no real reason, a history
 * that disagrees with the committed ceiling, a reworded pointer this gate cannot
 * parse, a `--write-baseline` that would raise silently, and the dead scan root.
 * The dead-root case is the one a refactor is most likely to break silently — a
 * gate that scans nothing and exits green is exactly what `assertScanned` exists
 * for.
 *
 * The accepting cases are not filler. Three of them pin behaviour the ratchet
 * must NOT punish: a stated raise, a second raise that keeps the first row, and
 * a regeneration that only lowers. A ratchet with no accept cases drifts into
 * refusing legitimate work, which is how a gate stops being read.
 */
export function selfTest(repoRoot: string): number {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'rsc-selftest-'));
    const run = (shape: FixtureShape, args: readonly string[] = ['--quiet']): number => {
        const work = buildFixture(fs.mkdtempSync(path.join(root, 'case-')), shape);
        return runGateCli(repoRoot, SCRIPT_REL, args, work);
    };
    const padding = `\n${'Filler prose that is neither an Iron Law nor a negation clause. '.repeat(40)}\n`;

    const cases: SelfTestCase[] = [
        {
            name: 'a migrated rule at its ceiling with a resolving pointer passes',
            expect: 'accept',
            run: () => run({ rules: true, baseline: true }),
        },
        {
            name: 'a pointer whose target does not resolve is REFUSED',
            expect: 'reject',
            run: () => run({ rules: true, baseline: true, target: false }),
        },
        {
            name: 'a migrated rule padded past its ceiling is REFUSED',
            expect: 'reject',
            run: () => run({ rules: true, baseline: true, pad: padding }),
        },
        // The next two isolate the REASON requirement from the size check: no
        // padding, so the rule sits comfortably under its raised ceiling and the
        // only thing separating accept from reject is the sentence. That framing
        // is the whole point — the first implementation checked the reason only
        // when the rule was over its ceiling, which a raise by definition fixes,
        // so the check was unreachable and this suite is what surfaced it.
        {
            name: 'a raise whose reason is empty is REFUSED even when nothing is over its ceiling',
            expect: 'reject',
            run: () =>
                run({
                    rules: true,
                    baseline: true,
                    tamper: (b) => {
                        const at = b.ceilings['alpha'] ?? 0;
                        b.ceilings['alpha'] = at + 10_000;
                        b.history = [
                            { date: '2026-08-17', rule: 'alpha', from: at, to: at + 10_000, reason: 'raise' },
                        ];
                    },
                }),
        },
        {
            name: 'the same raise WITH a real reason sentence passes',
            expect: 'accept',
            run: () =>
                run({
                    rules: true,
                    baseline: true,
                    tamper: (b) => {
                        const at = b.ceilings['alpha'] ?? 0;
                        b.ceilings['alpha'] = at + 10_000;
                        b.history = [
                            {
                                date: '2026-08-17',
                                rule: 'alpha',
                                from: at,
                                to: at + 10_000,
                                reason:
                                    'A measured finding landed in this rule and its worked example ' +
                                    'is load-bearing, so the ceiling moves with the authored change.',
                            },
                        ];
                    },
                }),
        },
        {
            name: 'a history entry disagreeing with the committed ceiling is REFUSED',
            expect: 'reject',
            run: () =>
                run({
                    rules: true,
                    baseline: true,
                    tamper: (b) => {
                        const at = b.ceilings['alpha'] ?? 0;
                        b.history = [
                            {
                                date: '2026-08-17',
                                rule: 'alpha',
                                from: at,
                                to: at + 5_000,
                                reason:
                                    'A real sentence, so the only thing wrong here is that the ' +
                                    'committed ceiling was never regenerated to match the claim.',
                            },
                        ];
                    },
                }),
        },
        {
            // Risk 3 of the roadmap: 44 pointers were hand-written over months in
            // several phrasings, so a gate keyed to one phrasing silently stops
            // seeing the others. This case pins the opposite behaviour — a rule the
            // ledger's broad matcher sees and this gate cannot parse is a FINDING.
            name: 'a reworded pointer this gate cannot parse is REFUSED, not silently skipped',
            expect: 'reject',
            run: () =>
                run({
                    rules: true,
                    baseline: true,
                    rewordPointer: 'The body was migrated to the guideline on alpha mechanics.',
                }),
        },
        {
            // The HIGH finding of this change's own completion review. Without
            // this, assertion 3 is decorative: the failure text and the baseline
            // comment both send the operator to --write-baseline, which would
            // silently re-anchor the corpus upward.
            name: '--write-baseline REFUSES to raise a ceiling no history entry covers',
            expect: 'reject',
            run: () => run({ rules: true, baseline: true, pad: padding }, ['--write-baseline']),
        },
        {
            name: '--write-baseline accepts a LOWERING with no history entry at all',
            expect: 'accept',
            run: () =>
                run(
                    {
                        rules: true,
                        baseline: true,
                        tamper: (b) => {
                            // Ceiling far above the tree: the regeneration lowers it.
                            b.ceilings['alpha'] = (b.ceilings['alpha'] ?? 0) + 5_000;
                        },
                    },
                    ['--write-baseline'],
                ),
        },
        {
            // A second raise used to red the gate permanently, because the first,
            // correct, historical entry disagreed with the committed ceiling.
            name: 'a SECOND raise for the same rule leaves the earlier entry intact and passes',
            expect: 'accept',
            run: () =>
                run({
                    rules: true,
                    baseline: true,
                    tamper: (b) => {
                        const at = b.ceilings['alpha'] ?? 0;
                        b.ceilings['alpha'] = at + 2_000;
                        b.history = [
                            {
                                date: '2026-08-17',
                                rule: 'alpha',
                                from: at,
                                to: at + 1_000,
                                reason:
                                    'First raise: a measured finding landed and its worked example ' +
                                    'is load-bearing, so the ceiling moved with the authored change.',
                            },
                            {
                                date: '2026-08-18',
                                rule: 'alpha',
                                from: at + 1_000,
                                to: at + 2_000,
                                reason:
                                    'Second raise: a further finding landed in the same rule, and ' +
                                    'the audit trail keeps both rows rather than overwriting one.',
                            },
                        ];
                    },
                }),
        },
        {
            name: 'a dead scan root is REFUSED rather than reported clean',
            expect: 'reject',
            run: () => run({ rules: false, baseline: true }),
        },
    ];

    return runSelfTest({
        gate: GATE,
        cases,
        minCases: SELF_TEST_MIN_CASES,
        minRejectCases: SELF_TEST_MIN_REJECT,
    });
}

if (process.argv[1] && import.meta.url === pathToFileURL(fileURLToPath(import.meta.url)).href) {
    const invoked = path.resolve(process.argv[1]);
    const self = path.resolve(fileURLToPath(import.meta.url));
    if (invoked === self) process.exit(main());
}
