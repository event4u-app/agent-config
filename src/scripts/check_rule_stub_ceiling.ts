#!/usr/bin/env tsx
/**
 * check_rule_stub_ceiling — hold a migrated rule at the size its pointer claims.
 *
 * ## The defect
 *
 * 42 of this package's 117 rules carry a line of the shape *"Body migrated to
 * `guideline:X` … Trigger-set above activates this routing on demand"*. The
 * projection half of that pattern is real (`type: manual` → `_is_manual_rule`,
 * `condense.ts`), and the migration ledger (`lint_rule_migration_ledger.ts`)
 * records where each pre-migration heading WENT.
 *
 * **Nothing asserted that a migrated rule stays small.** Migration was executed
 * as an event and never encoded as a state, so those pointers are hand-authored
 * prose no gate reads. The sharpest case, measured at adoption:
 * `src/rules/context-hygiene.md` is 10,988 B and declares its body migrated to
 * `context-hygiene-mechanics.md`, which is 3,491 B — the rule is three times the
 * size of the file it migrated into.
 *
 * The aggregate census ratchet (`check_rule_activation_census`) does not catch
 * this and is not meant to: it pins the CORPUS total with a 2,000-token drift
 * allowance, so one rule growing while another shrinks is a green run. Measured
 * at the time of writing, the corpus sits 411 tokens ABOVE its pinned baseline
 * and that gate is green. Per-rule re-growth under an aggregate cap is the gap.
 *
 * ## What this gate asserts
 *
 * 1. **The pointer's target resolves.** Every `migrated to` / `merged into`
 *    target — markdown link href or backticked `skill:` / `guideline:` /
 *    `context:` / path token — names a file that exists.
 * 2. **The rule is under its own ceiling.** A per-rule exact-BPE token ceiling
 *    read from `src/config/rule-stub-ceilings.json`, generated by
 *    `--write-baseline` and never hand-edited. Shrink-only, same posture as the
 *    census token axis one level finer.
 * 3. **A raise is a stated decision.** A ceiling above the committed one needs a
 *    `history` entry whose `reason` is a real sentence. Raising a ceiling to
 *    clear a red is the config-weakening move this repo blocks by construction.
 *
 * ## What it deliberately does NOT assert
 *
 * - **Not which prose should move.** That is `road-to-standing-context-40k`
 *   step 2.2. This gate measures and holds a line; it never proposes a deletion,
 *   and `preservation-guard` forbids one — a ceiling is satisfied by MOVING.
 * - **Not that a rule at its ceiling is correct.** The ceilings are a
 *   floor-plus-residue snapshot taken at adoption. A rule at its ceiling is not
 *   thereby right, only not worse.
 * - **Not the pointer's semantic accuracy.** That the target resolves is
 *   checkable; that it received the right prose is the migration ledger's
 *   completeness property, already gated next door.
 * - **Not a cross-commit ratchet.** The gate reads ONE tree state, so it cannot
 *   see the previous baseline. "Shrink-only" therefore means: the tree must sit
 *   under the committed ceiling, and every ceiling the history says was RAISED
 *   carries a real reason. A ceiling silently lowered — or raised with no history
 *   entry at all — is a diff-scoped question this gate does not answer; code
 *   review of the baseline diff does. Saying so is the point: implying a
 *   cross-commit guarantee it cannot give is the coverage inflation this repo's
 *   enforcement audit exists to remove.
 * - **Not a phrasing convention.** The pointer set is cross-checked against
 *   `migratedRules()` — the ledger gate's own broad matcher — and a rule that
 *   matcher sees while this one cannot parse is reported as a FINDING, never as
 *   silence. That is the whole mitigation for keying a gate to hand-authored
 *   prose written over months in several phrasings.
 *
 * ## The floor/residue split is reported, not enforced
 *
 * `--report` splits each migrated rule's retained body into **floor** (what
 * `preservation-guard` requires to stay: Iron Law headings at their level, the
 * fenced blocks inside those sections byte-for-byte, capitalised negation
 * clauses, plus the pointer sentence) and **residue** (everything else). The
 * split is a judgment with a mechanical criterion, and it is published per rule
 * WITH the criterion so a reader can disagree with one row without discarding
 * the total. No gate verdict depends on it — it is Phase 3's handover input.
 *
 * Exit codes: 0 = clean, 1 = violations, 2 = usage.
 */
