#!/usr/bin/env tsx
/**
 * egress_sender_census.ts — regenerate the sender census in
 * docs/contracts/egress-placeholders-v1.md from the tree, or report that the
 * committed copy has drifted from it.
 *
 *   ./scripts-run src/scripts/egress_sender_census           # exit 1 on drift
 *   ./scripts-run src/scripts/egress_sender_census --write   # rewrite the region
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import process from 'node:process';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { coverageFromTree } from './_lib/egress_coverage.js';
import { renderTable, SCAN_ROOTS, scanSenders } from './_lib/egress_sender_scan.js';

const HERE = fileURLToPath(import.meta.url);
const ROOT = path.resolve(path.dirname(HERE), '..', '..');

export const DOC_REL = 'docs/contracts/egress-placeholders-v1.md';
export const BEGIN_MARKER = '<!-- BEGIN egress-sender-census (generated) -->';
export const END_MARKER = '<!-- END egress-sender-census -->';
export const COVERAGE_BEGIN = '<!-- BEGIN egress-coverage (generated) -->';
export const COVERAGE_END = '<!-- END egress-coverage -->';

/** The coverage table region (placeholders 6.3), regenerated beside the census it reads. */
export function renderCoverageRegion(repoRoot: string): string {
    return [
        '> Generated by `egress_sender_census` from `host_lowering.yaml`, the probe records it',
        '> cites and the sender census above. Do not edit between the markers; regenerate with',
        '> `./scripts-run src/scripts/egress_sender_census --write`. `agent-config hooks:status` prints it.',
        '',
        coverageFromTree(repoRoot),
    ].join('\n');
}

export function renderRegion(repoRoot: string): string {
    return [
        '> Generated by `egress_sender_census`. Do not edit between the markers;',
        '> regenerate with `./scripts-run src/scripts/egress_sender_census --write`.',
        '',
        `Scanned: ${SCAN_ROOTS.map((r) => `\`${r}/\``).join(', ')}, TypeScript and shell, tests excluded.`,
        'A module whose endpoint is computed at runtime **and** whose send shape the',
        'scanner does not recognise is absent from this table; that residual is why',
        '`unclassified` exists. `content` stays `undeclared` until the module carries an',
        '`egress-content:` marker, and `engine` counts a direct import of a function that detects or replaces',
        '(`detect`, `findSpans`, `replaceSpans`, `replaceValues`); importing a table constant does not count.',
        '',
        renderTable(scanSenders(repoRoot)),
    ].join('\n');
}

export function extractRegion(doc: string, open: string = BEGIN_MARKER, close: string = END_MARKER): string | null {
    const begin = doc.indexOf(open);
    const end = doc.indexOf(close);
    if (begin === -1 || end === -1 || end < begin) return null;
    return doc.slice(begin + open.length, end).trim();
}

export function spliceRegion(doc: string, region: string, open: string = BEGIN_MARKER, close: string = END_MARKER): string {
    const begin = doc.indexOf(open);
    const end = doc.indexOf(close);
    if (begin === -1 || end === -1 || end < begin) {
        throw new Error(`egress_sender_census: markers missing in ${DOC_REL}`);
    }
    return `${doc.slice(0, begin)}${open}\n${region}\n${doc.slice(end)}`;
}

export function main(argv: readonly string[] = process.argv.slice(2), repoRoot: string = ROOT): number {
    const docPath = path.join(repoRoot, DOC_REL);
    const doc = fs.readFileSync(docPath, 'utf-8');
    const region = renderRegion(repoRoot);
    const coverage = renderCoverageRegion(repoRoot);
    if (argv.includes('--write')) {
        fs.writeFileSync(docPath, spliceRegion(spliceRegion(doc, region), coverage, COVERAGE_BEGIN, COVERAGE_END));
        process.stdout.write(`egress_sender_census: wrote ${DOC_REL}\n`);
        return 0;
    }
    const committed = extractRegion(doc);
    if (committed !== region.trim() || extractRegion(doc, COVERAGE_BEGIN, COVERAGE_END) !== coverage.trim()) {
        process.stderr.write(
            `egress_sender_census: the census in ${DOC_REL} differs from the tree — ` +
                'run ./scripts-run src/scripts/egress_sender_census --write\n',
        );
        return 1;
    }
    process.stdout.write('egress_sender_census: census matches the tree\n');
    return 0;
}

function isCliEntry(): boolean {
    if (process.argv[1] === undefined) return false;
    if (import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) return true;
    try {
        return fs.realpathSync(HERE) === fs.realpathSync(path.resolve(process.argv[1]));
    } catch {
        return false;
    }
}

if (isCliEntry()) {
    process.exit(main());
}
