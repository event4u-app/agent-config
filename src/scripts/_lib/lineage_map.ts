/**
 * Two lineage views, deliberately unequal (council O6).
 *
 * The tracked view lives next to the repo's shared map and lists mechanisms by verdict —
 * nothing else. Not a source id, not an identity, not a per-source count: a list of what one
 * source fed is more identifying than the source's name would be.
 *
 * The source view is the owner's: source → mechanisms with identities decrypted, rendered
 * from the local ledger into the user-global home and never into a work tree.
 */

import type { MechanismRecord } from '../lint_harvest_provenance.js';
import type { Ledger } from './lineage_ledger.js';
import { latestDecisions, lineageFrom } from './lineage_query.js';

/** The tracked view's place: beside the shared map, carried over by every map redraw. */
export const LINEAGE_VIEW_REL = 'agents/map/lineage.md';

const VERDICT_ORDER: readonly MechanismRecord['verdict'][] = ['adopt', 'adapt', 'already', 'gap', 'deferred', 'reject'];

export function renderTrackedLineage(rows: readonly MechanismRecord[]): string {
    const latest = [...latestDecisions(rows).values()];
    const out = [
        '# Lineage — mechanisms by verdict',
        '',
        `Generated by \`code-graph map --lineage\` from \`provenance/mechanisms.jsonl\`: ${String(latest.length)} mechanism(s), latest decision each.`,
        '',
    ];
    for (const verdict of VERDICT_ORDER) {
        const group = latest.filter((r) => r.verdict === verdict).sort((a, b) => a.mechanism_id.localeCompare(b.mechanism_id));
        if (group.length === 0) continue;
        out.push(`## ${verdict} (${String(group.length)})`, '');
        for (const r of group) {
            const where = r.realised_in?.length ? ` — ${r.realised_in.map((p) => `\`${p}\``).join(', ')}` : '';
            const owner = r.roadmap ? ` — owner \`${r.roadmap}\`` : '';
            out.push(`- \`${r.mechanism_id}\` (${r.decided_at})${where}${owner}`);
        }
        out.push('');
    }
    return out.join('\n');
}

export function renderSourceLineage(ledger: Ledger, keys: readonly string[], rows: readonly MechanismRecord[]): string {
    const out = ['# Lineage — sources (local, never shared)', ''];
    for (const s of [...ledger.sources].sort((a, b) => a.source_id.localeCompare(b.source_id))) {
        const found = lineageFrom(ledger, s.source_id, keys, rows);
        if (found === null) continue;
        out.push(`## ${s.source_id} — ${found.identity}`, '', `kind ${s.kind} · license ${s.license} · watch ${s.watch ? 'on' : 'off'}`, '');
        for (const m of found.mechanisms) {
            out.push(`- ${m.mechanism_id} — ${m.verdict ?? 'no decision'} — pin ${m.pin}${m.locator ? ` — at ${m.locator}` : ''}`);
        }
        out.push('');
    }
    return out.join('\n');
}
