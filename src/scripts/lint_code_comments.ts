#!/usr/bin/env node
/**
 * lint_code_comments — the carrier `code-comment-discipline` and the
 * "Code comments English" clause of `language-and-tone` never had.
 *
 * Both rules existed and neither could fire on the thing they govern.
 * `language-and-tone` is a kernel rule and names one enforcer,
 * `check_md_language.ts`, which rejects every path that is not `.md`
 * (`check_md_language.ts:175`) — so the code clause carried an `enforced_by`
 * entry that structurally cannot see a source file. `code-comment-discipline`
 * is `type: auto` and matches PROMPT keywords, so a run that writes forty-five
 * files without the user typing "comment", "refactor" or "implement" never
 * loads it at all. Measured 2026-09-02 in a consumer repository: 40 of 45
 * changed source files carried German comment lines, one of them a 101-line
 * colour-analysis report inside a CSS file.
 *
 * Three classes, each keyed on STRUCTURE rather than on a judgement about
 * prose, because a gate that has to decide whether a comment is "useful" is a
 * gate nobody can predict:
 *
 *   1. `de-comment`      — a comment line carrying German. Two independent
 *                          signals: a German-specific character, or two or
 *                          more German function words on one line.
 *   2. `report-comment`  — a comment block shaped like an analysis report.
 *                          The five literal patterns are in REPORT_SIGNALS,
 *                          named there rather than quoted here so this header
 *                          does not trip its own gate. Length is deliberately
 *                          NOT a signal; a long comment can be one long WHY.
 *   3. `provenance-comment` — a comment explaining where the code came from:
 *                          a roadmap path, a phase-and-step citation, a
 *                          prototype or reference artefact path. Evidence
 *                          belongs in the roadmap that asked for it, and a
 *                          second copy in the source is the copy in the wrong
 *                          place.
 *
 * Escape, per line or per file:
 *   code-comment-allow <class> -- <reason>
 * A reason is mandatory; the bare marker does not suppress.
 *
 * Scope is the DIFF by default, so a pre-existing tree does not turn red.
 * `--paths` and `--root` exist for auditing a tree the gate does not own.
 *
 * STATED RECALL LIMIT, found by running the gate against its own first output
 * rather than by reasoning about it. A straight `"` left unpaired on a line is
 * ambiguous — it opens a quotation that continues, or closes one that began
 * above — and the gate reads it as an opener and stops scanning the rest of
 * the line. That is right for an English sentence introducing a German quote
 * and wrong for a German continuation whose opener sits on an earlier line.
 * Typographic marks carry direction and do not have the ambiguity. The cost is
 * a miss, never a false positive, and the answer is a second instrument: a
 * plain word sweep over every changed file with no comment detection at all
 * caught three lines this classifier could not, and both were run to zero
 * before the tree was called clean. A gate that has been wrong once is not a
 * gate to verify with alone.
 *
 * Exit codes: 0 clean · 2 findings · 1 usage or internal error.
 *
 * `--self-test` drives this binary over {@link COMMENT_CASES}, the one fixture
 * table the vitest suite also enumerates. A gate that reports a `scanned:`
 * count has proven it read something; only a case that must REJECT proves the
 * reading changes the verdict, and only a shared table keeps the two corpora
 * from drifting apart.
 */
