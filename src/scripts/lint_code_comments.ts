/**
 * Drive the real binary over every fixture.
 *
 * Shells out rather than calling {@link scanText} in-process, because the
 * thing a contributor runs is the CLI — its argv parsing, its scan-scope
 * assertion and its exit codes included. The vitest suite covers the pure
 * classifier; this covers the binary that ships.
 *
 * The floors are set just under the table's real size, so deleting a case to
 * reach green fails instead, and any deliberate shrink shows up as a floor
 * edit a reviewer reads in the diff.
 */
export function selfTest(): number {
    const repoRoot = path.resolve(path.dirname(_HERE), '..', '..');
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'lcc-selftest-'));
    const exercise = (testCase: CommentCase, index: number): number => {
        const file = path.join(dir, `case-${String(index)}.ts`);
        fs.writeFileSync(file, testCase.source, 'utf-8');
        return runGateCli(repoRoot, 'src/scripts/lint_code_comments.ts', ['--paths', file], dir);
    };
    try {
        return runSelfTest({
            gate: 'lint_code_comments',
            minCases: 16,
            minRejectCases: 8,
            cases: COMMENT_CASES.map((testCase, index) => ({
                name: testCase.name,
                expect: testCase.flags.length > 0 ? ('reject' as const) : ('accept' as const),
                run: () => exercise(testCase, index),
            })),
        });
    } finally {
        fs.rmSync(dir, { recursive: true, force: true });
    }
}

const HELP = `usage: lint_code_comments [--base <ref>] [--root <dir>] [--paths <f> …] [--report]

  --base <ref>   diff against this ref (default: origin/main)
  --root <dir>   run against another checkout (default: this repository)
  --paths        scan exactly these files, ignoring the diff
  --report       print every finding grouped by file and exit 0
  --self-test    drive this binary over its own fixture table and exit 0 on pass

Classes: de-comment · report-comment · provenance-comment
Escape:  code-comment-allow <class|*> -- <reason>   (per line)
         code-comment-allow-file -- <reason>        (first 2000 chars)
`;

export function main(argv: string[]): number {
    // `--help` wins, and the recursion guard is not decoration: `runGateCli`
    // sets GATE_SELF_TEST_CHILD precisely so a child cannot re-enter the suite.
    // Latent today because the child's argv is `--paths <file>`, but any later
    // change that forwards the parent's argv would recurse 18-way per level.
    if (argv.includes('--help') || argv.includes('-h')) {
        process.stdout.write(HELP);
        return 0;
    }
    if (argv.includes('--self-test')) {
        if (process.env['GATE_SELF_TEST_CHILD'] === '1') {
            process.stderr.write('lint_code_comments: refusing to nest --self-test inside a self-test child\n');
            return 2;
        }
        return selfTest();
    }
    let base = 'origin/main';
    let root = path.resolve(path.dirname(_HERE), '..', '..');
    let reportOnly = false;
    const explicit: string[] = [];

    for (let i = 0; i < argv.length; i++) {
        const a = argv[i];
        if (a === '--help' || a === '-h') { process.stdout.write(HELP); return 0; }
        else if (a === '--base') { base = argv[++i] ?? ''; }
        else if (a === '--root') { root = path.resolve(argv[++i] ?? '.'); }
        else if (a === '--report') { reportOnly = true; }
        else if (a === '--paths') { while (i + 1 < argv.length && !argv[i + 1]!.startsWith('--')) explicit.push(argv[++i]!); }
        else { process.stderr.write(`lint_code_comments: unknown argument ${a}\n${HELP}`); return 1; }
    }
    if (!base && explicit.length === 0) { process.stderr.write('--base needs a ref\n'); return 1; }

    const candidates = (explicit.length > 0 ? explicit : changedFiles(root, base)).filter(isScannable);
    // Whole file when a caller named the path; only the lines the diff added
    // when the scope IS the diff — see `addedLineMap` for the measured reason.
    const added = explicit.length > 0 ? null : addedLineMap(root, base);
    const findings: CommentFinding[] = [];
    for (const rel of candidates) {
        const abs = path.isAbsolute(rel) ? rel : path.join(root, rel);
        let text: string;
        try { text = fs.readFileSync(abs, 'utf-8'); } catch { continue; }
        const all = scanText(rel, text);
        findings.push(...(added ? findingsOnAddedLines(all, added.get(rel)) : all));
    }

    try {
        reportScanned({
            gate: 'lint_code_comments',
            scanned: candidates.length,
            units: 'source file(s)',
            roots: explicit.length > 0 ? explicit.slice(0, 4) : [`git diff ${base}...HEAD`],
            allowEmpty:
                'EMPTY_VALID: the scan root is a DIFF, and a diff with no source file in it is the ' +
                'normal case for a docs-only or config-only change. git already answered for the ' +
                'range: an unreadable ref yields no candidates AND no findings, which is ' +
                'indistinguishable here from a clean docs commit, so this gate deliberately does ' +
                'not treat zero as a dead scope. The scope failure this class exists to catch — a ' +
                'moved source tree — cannot occur, because there is no committed path list to go ' +
                'stale.',
        });
    } catch (e) {
        if (e instanceof DeadScopeError) {
            process.stderr.write(`❌  ${e.message}\n`);
            return 1;
        }
        throw e;
    }
    process.stdout.write(`  against ${explicit.length > 0 ? 'an explicit path list' : base}\n`);
    if (findings.length === 0) {
        process.stdout.write('✅  lint_code_comments: no German, report-shaped or provenance comments.\n');
        return 0;
    }

    const byFile = new Map<string, CommentFinding[]>();
    for (const f of findings) { const l = byFile.get(f.file) ?? []; l.push(f); byFile.set(f.file, l); }
    for (const [file, list] of [...byFile].sort()) {
        process.stdout.write(`\n${file}  (${list.length})\n`);
        for (const f of list.slice(0, 8)) {
            process.stdout.write(`  ${String(f.line).padStart(5)}  ${f.cls}/${f.signal}  ${f.snippet}\n`);
        }
        if (list.length > 8) process.stdout.write(`  … ${list.length - 8} more in this file\n`);
    }
    const counts = new Map<string, number>();
    for (const f of findings) counts.set(f.cls, (counts.get(f.cls) ?? 0) + 1);
    process.stdout.write(`\n${[...counts].map(([c, n]) => `${c}: ${n}`).join(' · ')} across ${byFile.size} file(s)\n`);

    if (reportOnly) return 0;
    process.stderr.write(
        '\n❌  lint_code_comments: comments carry language, evidence or report structure that does not belong in source.\n' +
        '    A comment states a WHY or a constraint the code cannot show, in English. Evidence belongs in the\n' +
        '    roadmap that asked for it. Rewrite the comment, delete it, or escape one line with\n' +
        '    `code-comment-allow <class> -- <reason>`.\n',
    );
    return 2;
}

const _isMain = (() => {
    const entry = process.argv[1];
    if (!entry) return false;
    try { return fs.realpathSync(entry) === fs.realpathSync(_HERE); } catch { return false; }
})();

if (_isMain) process.exit(main(process.argv.slice(2)));
